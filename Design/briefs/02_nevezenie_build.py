"""Сборка уровня 02_nevezenie («Акт II. Невезение»).

Запуск из корня репозитория:  python3 Design/briefs/02_nevezenie_build.py

Замысел: всё рушится под шариком. Фирменная механика — рассыпающиеся блоки X
(три моста разной длины + «лестница» осыпающихся уступов), вторая — гриб-батут O.
Вертикаль: высокое плато (y=11) → спуск по осыпающимся уступам в долину (y=3)
→ гриб-батут на арену Лунного Оленя (y=9) → обрыв к двери (y=3).

Ритм (колонки):
   0..24   плато, спокойная трава, intro, осколок №1; пресс C на открытом месте (реплика 1)
  25..28   мост №1 — короткий X над бездной (4 кл.)
  29..44   шипы ^^ очередью (реплика 2), люк TT над неглубокой ямой с полом (реплика 3), K
  45..58   «лестница» из трёх осыпающихся уступов X вниз в долину; сорвался — лепёшка
  59..84   долина: пещерный козырёк, K, мост №2 (X, 5 кл.) под ПРЕССОМ — прижал = мост осыпался,
           пружина J на открытом месте (реплика 4, лепёшка), платформа-полка
  82..86   гриб-батут OO за 2–3 клетки до стены высотой 6
  85..110  арена Лунного Оленя: 26 клеток ровного пола, K, осколок №2 над Оленем (реплики 5–7)
 111..117  мост №3: X-X-X | столб с ВЕНТИЛЯТОРОМ | X-X-X над бездной — подбросит и уронит на мост
 118..139  уступ, обрыв 9→3 (лепёшка), нависающая глыба-«обвал», ступенька, дверь
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "Tools/levels"))
from gridkit import Grid  # noqa: E402

W, H = 140, 18
g = Grid(W, H)

# ---------------------------------------------------------------- 0..44: высокое плато (шарик стоит на y=11)
g.ground(0, 24, 11)
g.put("S", 2, 11)
g.put("*", 8, 12)                        # осколок №1 над спокойной травой
g.put("C", 19, 15)                       # пресс на открытом месте, падает на 4 клетки
g.block(22, 24, 14, 15)                  # низкий козырёк перед первым мостом — «коридор»
g.block(10, 12, 16, 17)                  # облачная скала сверху, рваный край неба

# мост №1: короткий, 4 клетки над бездной
for x in range(25, 29):
    g.put("X", x, 10)

g.ground(29, 44, 11)
g.put("^", 33, 11)                       # шипы очередью
g.put("^", 34, 11)
# неглубокая яма с полом под люком: колонки 38..39, пол на y=8
g.fill(38, 39, 8, 10, ".")
g.put("T", 38, 10)
g.put("T", 39, 10)
g.put("K", 43, 11)
g.fill(29, 31, 0, 3, ".")                # подмытый край плато: пещерный карман снизу

# пещерные карманы в толще плато (декор, не на пути): рваный, не прямоугольный массив
g.fill(4, 18, 3, 6, ".")
g.fill(7, 15, 7, 7, ".")
g.fill(6, 16, 2, 2, ".")

# ---------------------------------------------------------------- 45..58: осыпающаяся лестница в долину
g.ground(45, 84, 3)                      # дно долины (шарик стоит на y=3)
for k in range(3):                       # уступы вплотную «по диагонали»: скатился с одного — упал на следующий
    for x in range(45 + 3 * k, 48 + 3 * k):
        g.put("X", x, 8 - 2 * k)         # уступы на y=9, 7, 5
g.fill(45, 47, 3, 3, "#")                # обломки у подножия плато

# ---------------------------------------------------------------- 59..84: долина
g.block(59, 64, 9, 10)                   # пещерный козырёк — въезд в долину
g.block(60, 62, 8, 8)
g.put("K", 60, 3)
for x in range(61, 65):
    g.put(">", x, 2)                     # конвейер разгоняет прямо на мост под прессом
# мост №2: 5 клеток над бездной, над ним пресс — прижмёт шарика, мост осыпется
g.pit(65, 69)
for x in range(65, 70):
    g.put("X", x, 2)
g.put("C", 67, 8)
# пружина на открытом месте: подбросит на ~8 и уронит — лепёшка
g.put("J", 75, 3)
g.platform(78, 80, 7)                    # полка-передышка над долиной
# гриб-батут за 2–3 клетки до высокой стены
g.put("O", 82, 2)
g.put("O", 83, 2)

# ---------------------------------------------------------------- 85..110: арена Лунного Оленя (y=9)
g.ground(85, 110, 9)
g.put("K", 87, 9)
g.put("B", 96, 9)                        # Олень ходит 90..102 — пол ровный на всей длине
g.put("*", 94, 10)                       # осколок №2 прямо перед Оленем
g.block(84, 86, 16, 17)                  # рваный край неба над ареной (4+ пустоты над Оленем сохраняются)
g.put("K", 107, 9)
g.fill(89, 106, 3, 6, ".")               # грот под ареной (декор): Олень топает по «крыше»
g.fill(92, 103, 7, 7, ".")

# ---------------------------------------------------------------- 111..117: мост №3 с вентилятором
g.pit(111, 117)
for x in (111, 112, 113, 115, 116, 117):
    g.put("X", x, 8)
g.fill(114, 114, 0, 8, "#")              # тонкий столб посреди пропасти
g.put("W", 114, 9)                       # подбросит — и уронит на осыпающийся мост

# ---------------------------------------------------------------- 118..139: обрыв к двери
g.ground(118, 121, 9)
g.ground(122, 139, 3)                    # обрыв 9→3: лепёшка
g.block(126, 130, 11, 12)                # нависающая глыба — «обвал вот-вот»
g.block(127, 129, 10, 10)
g.ground(131, 139, 5)                    # ступенька к двери
g.put("F", 137, 5)

