#!/usr/bin/env python3
"""Сборка уровня 05_shvy «Акт V. Швы мира». Запуск из корня репозитория:
    python3 Design/briefs/05_shvy_build.py

Фирменная механика — ПОРТАЛЫ @ (3 пары): мир порван «швами» — стенами до неба и
бездонной щелью, которые можно только «перешагнуть» через портал. Плюс рассыпающиеся
блоки X («битые пиксели»), гриб O у высокой стены, конвейер и лёд.

Ритм (x):
  0..20    старт на уступе, «мигающий» шов из платформ над бездной (один кусок — битый X)
  21..34   конвейер под прессом C на открытом месте
  35..38   рассыпающийся мост X над бездной
  39..50   осколок 1, связка шипов, вход портала 1 перед «швом»-стеной до неба
  51..54   ШОВ: стена до потолка мира
  55..71   портал 1 выводит на парящий остров (y=15); пресс; спуск по островам; вентилятор
  72..89   лепёшка с острова на землю (8 кл.), чекпоинт, пружина под открытым небом, гриб
  90..98   плато на высоте 10 (гриб-прыжок), чекпоинт, лёд к порталу 2 у края щели
  99..108  бездонная щель (10 кл.) — только порталом
  109..136 арена Кодового Червя: 28 кл. ровного пола; портал 2 выводит прямо в неё
  137..140 портал 3 и второй шов-стена
  141..159 остров-КОПИЯ первого острова (y=16), люк, лепёшка к двери, шипы, осколок 3
"""
import sys

sys.path.insert(0, "Tools/levels")
from gridkit import Grid  # noqa: E402

W, H = 160, 20
g = Grid(W, H)


def island(x0, top, extra=True):
    """Парящий остров (8 клеток) с рваным низом. Одинаковая форма — «копипаста мира»."""
    g.block(x0, x0 + 7, top - 2, top - 1)
    if extra:
        g.block(x0 + 2, x0 + 5, top - 3, top - 3)
        g.block(x0 + 3, x0 + 4, top - 4, top - 4)


# --- 0..20: старт и «мигающий» шов из платформ над бездной
g.ground(0, 6, 6)
g.put("S", 2, 6)
g.platform(9, 10, 5)
g.fill(13, 14, 5, 5, "X")          # битый пиксель в цепочке
g.platform(17, 18, 6)
g.block(11, 12, 11, 11)            # обрывки мира висят над швом
g.block(16, 16, 13, 13)

# --- 21..34: конвейер под прессом
g.ground(21, 34, 6)
g.fill(24, 31, 5, 5, ">")
g.put("C", 28, 10)
g.block(22, 26, 14, 15)            # «повтор» стартового уступа висит в небе
g.block(22, 23, 13, 13)

# --- 35..38: рассыпающийся мост над бездной
g.fill(35, 38, 5, 5, "X")

# --- 39..50: осколок 1, шипы, портал 1
g.ground(39, 50, 6)
g.put("*", 41, 6)
g.put("^", 44, 6)
g.put("^", 45, 6)
g.put("^", 46, 6)
g.put("@", 50, 6)                  # вход 1

# --- 51..54: ШОВ — стена до потолка мира (с «щелями» — битыми пикселями)
g.block(51, 54, 0, 17)
g.fill(52, 53, 9, 9, ".")
g.fill(52, 52, 13, 13, ".")

# --- 55..71: верхний ярус: остров-1 с выходом портала, пресс, остров-2 с вентилятором
island(56, 15)
g.put("@", 57, 15)                 # выход 1
g.put("C", 61, 18)
g.put("K", 59, 15)
g.block(66, 71, 10, 11)            # остров-2, верх на 12
g.block(68, 70, 9, 9)
g.put("W", 69, 12)

# --- 72..89: лепёшка вниз, чекпоинт, пружина под открытым небом, гриб у стены
g.ground(72, 89, 4)
g.put("K", 75, 4)
g.put("J", 82, 4)
g.fill(87, 88, 3, 3, "O")

# --- 90..98: плато (гриб-прыжок на 6), лёд к порталу 2 у края щели
g.ground(90, 98, 10)
g.put("K", 92, 10)
g.fill(94, 96, 9, 9, "~")
g.put("@", 97, 10)                 # вход 2
g.block(92, 94, 16, 16)            # висящий пиксель

# --- 99..108: бездонная щель (только порталом)

# --- 109..136: арена Червя
g.ground(109, 136, 4)
g.put("@", 110, 4)                 # выход 2 — прямо в арену
g.put("K", 112, 4)
g.put("B", 122, 4)
g.put("*", 126, 4)
g.block(114, 117, 13, 13)          # «дубли» висят высоко над ареной
g.block(126, 129, 15, 15)
g.put("@", 136, 4)                 # вход 3

# --- 137..140: второй шов-стена
g.block(137, 140, 0, 17)
g.fill(138, 139, 7, 7, ".")
g.fill(139, 139, 12, 12, ".")

# --- 141..159: остров-КОПИЯ, люк, лепёшка к двери
island(142, 16)
g.put("@", 143, 16)                # выход 3
g.block(150, 155, 12, 12)          # остров-4 вплотную к копии, верх на 13, под люком пусто
g.put("T", 153, 12)
g.ground(150, 159, 4)
g.block(151, 151, 11, 11)          # рваный низ острова-4
g.put("^", 157, 4)
g.put("*", 158, 4)
g.put("F", 159, 4)

