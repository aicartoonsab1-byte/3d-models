"""Сборка уровня 01_rozhdenie («Акт I. Рождение»).

Запуск из корня репозитория:  python3 Design/briefs/01_rozhdenie_build.py
Ритм (h — высота земли, шарик стоит на y=h):
   0..12  луг h=4, старт, осколок №1
  13..15  первая яма (бездна)
  16..30  холмики h=4→5→6, нависающая скала-козырёк, шипы ^ на пригорке (реплика 2)
  31..35  гриб-батут O за 3 клетки до стены высокого холма
  36..48  вершина холма h=11, пресс C (реплика 3)
  49..    обрыв 11→4: лепёшка №1
  49..55  долина, чекпоинт K
  56..68  пещерный карман под нависающей скалой, люк T над бездонной щелью, осколок №2
  69..79  рассыпающийся мостик X над неглубокой ямой, шипы ^ после него
  80..92  островки над бездной (вверх по ступеням)
  93..99  пружина J на высоком лугу (реплика 4) — улёт вверх и лепёшка №2
 100..109 спуск к двери F
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "Tools/levels"))
from gridkit import Grid  # noqa: E402

W, H = 110, 16
g = Grid(W, H)

# --- 0..12: луг, старт
g.ground(0, 12, 4)
g.put("S", 2, 4)
g.put("*", 9, 5)                      # осколок №1 — над травой, на пути
# 13..15 — первая яма (бездна)

# --- 16..30: холмики и козырёк
g.ground(16, 20, 4)
g.ground(21, 25, 5)
g.ground(26, 35, 6)
g.block(17, 21, 8, 9)                 # нависающая скала над лугом: коридорчик
g.put("^", 24, 5)                     # шипы на пригорке

# --- 31..35: гриб-батут перед высоким холмом
g.put("O", 33, 5)                     # гриб — верхний блок земли, шарик стоит на y=6

# --- 36..48: высокий холм
g.ground(36, 48, 11)
g.fill(36, 36, 11, 11, "#")           # рваный край у стены
g.put("C", 42, 14)                    # пресс над вершиной

# --- 49..55: долина после обрыва (лепёшка №1: 11→4)
g.ground(49, 68, 4)
g.put("K", 52, 4)

# --- 56..68: пещерный карман под скалой
g.block(56, 68, 7, 10)                # толстая нависающая скала, проход высотой 3
g.fill(56, 57, 10, 10, ".")           # скруглим вход
g.fill(67, 68, 10, 10, ".")
g.fill(62, 62, 0, 3, ".")             # бездонная щель
g.put("T", 62, 3)                     # люк над щелью
g.fill(58, 59, 3, 3, ".")             # ложбинка в полу пещерки — прокатиться
g.put("*", 60, 5)                     # осколок №2 в пещерке

# --- 69..79: рассыпающийся мостик над неглубокой ямой
g.ground(69, 79, 4)
g.fill(71, 74, 1, 3, ".")             # яма глубиной 3 с полом (не смертельна)
g.fill(71, 74, 3, 3, "X")             # мостик
g.put("^", 77, 4)                     # шипы сразу за мостиком

# --- 80..92: островки над бездной, по ступеням вверх
# 80..81 бездна
g.block(82, 84, 3, 5)                 # остров 1: стоим на y=6
# 85..86 бездна
g.block(87, 89, 5, 7)                 # остров 2: стоим на y=8
g.platform(91, 92, 8)                 # тонкая платформа
# --- 93..99: высокий луг с пружиной
g.ground(93, 100, 8)
g.fill(93, 100, 0, 1, "#")
g.put("J", 96, 8)

# --- 100..109: спуск к двери
g.ground(101, 104, 6)
g.ground(105, 109, 4)
g.put("F", 108, 4)

