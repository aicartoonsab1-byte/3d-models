g.put("T", 54, 2)                 # ловушка 4: люк посреди моста
g.block(57, 59, 0, 2)

# --- 59..70: подъём к острову с вентилятором
g.platform(61, 63, 4)             # стоит на 5
g.block(65, 71, 4, 6)             # стоит на 7
g.fill(66, 70, 3, 3)
g.put("W", 67, 7)                 # ловушка 5: вентилятор — подкинуть в пустоту
g.put("@", 70, 7)                 # портал 2: вход (до острова справа +4 — не допрыгнуть)

# --- 73..82: остров перед ядром (стоит на 11), гриб у стены
g.block(73, 82, 8, 10)
g.fill(74, 81, 7, 7)
g.put("@", 75, 12)                # портал 2: выход
g.put("O", 80, 10)                # гриб-батут, до стены ядра 3 клетки

# --- 83..119: ядро (стоит на 17)
g.block(83, 119, 12, 16)
g.fill(83, 119, 8, 11)            # стена ядра со стороны гриба
g.fill(86, 117, 6, 7)
g.fill(92, 110, 4, 5)
g.fill(97, 104, 2, 3)
g.put("K", 86, 17)
g.put("*", 101, 19)               # осколок №2 — перед Хранителем
g.put("B", 112, 17)               # ловушка 6: Хранитель, за 5 клеток до R
g.put("R", 117, 17)

# обрывки мира в пустоте (декор, вне пути)
g.block(28, 29, 18, 18)
g.block(45, 46, 12, 12)
g.put("=", 55, 15)
g.block(66, 66, 17, 18)
g.put("=", 90, 21)
g.block(3, 3, 4, 4)
g.block(110, 111, 0, 0)

