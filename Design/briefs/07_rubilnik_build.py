g.put("@", 32, 8)                 # портал 1: вход

# --- 38..58: дно пустоты (стоит на 3)
g.block(40, 51, 0, 2)
g.put("@", 41, 7)                 # портал 1: выход (падение на 4 клетки, без лепёшки)
g.put("K", 43, 3)
