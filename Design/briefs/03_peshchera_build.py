# осыпающийся край свода: дальше открывается «небо»
g.put("#", 88, 15)
g.put("#", 89, 15)

# ---------------------------------------------------------------- платформы к выходу
g.platform(91, 92, 7)     # стоять на y=8
g.platform(94, 95, 9)     # стоять на y=10

# ---------------------------------------------------------------- объекты
