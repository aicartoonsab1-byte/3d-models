# ---------------------------------------------------------------- ловушки (8 шт., акт III)
for x in (22, 26, 30):                 # одинаковые сталактиты-прессы
    g.put("C", x, 8)
g.put("W", 41, 6)                      # вентилятор: потолок на y=9 → удар об свод
for x in (50, 54, 58):                 # коридор шипов, между ними островки
    g.put("^", x, 8)
g.put("T", 81, 3)                      # люк над ямкой

