#!/usr/bin/env python3
"""Сборка уровня 06_bunt («Акт VI. Бунт»). Запуск из корня репозитория:

    python3 Design/briefs/06_bunt_build.py

Ритм:
  0–13    копия начала 01_rozhdenie: старт, первая яма шириной 2 на x=7..8 (реплика №1)
  14–25   ступени вверх, шипы, бездонная яма
  26–44   ПЛОТНЫЙ КЛАСТЕР «система нервничает»: шипы → люк над ямой → шипы → пресс (реплики №2, №3)
  45–52   башня (пресс над узкой вершиной) и падение-лепёшка на 7 клеток
  53–89   ПЕТЛЯ ДЕЖАВЮ: отрезок SEG (18 колонок) дважды подряд, между копиями чекпоинт (реплика №4, осколок №1)
  90–100  последняя трава: ровный участок без ловушек (реплика №5)
  100–110 финальный прыжок: пружина, люк над широкой ямой, приземление-лепёшка внизу (реплика №6)
  111–125 спокойный путь, осколок №2, дверь
"""
import sys

sys.path.insert(0, "Tools/levels")
from gridkit import Grid  # noqa: E402

W, H = 126, 14
BASE = 3                       # толща земли: шарик стоит на y=3
g = Grid(W, H)

# ---- 1. Копия начала уровня 1 ------------------------------------------------
g.ground(0, 6, BASE)
g.put("S", 2, BASE)
# яма 7..8 — «первая яма в жизни»
g.ground(9, 13, BASE)
g.put("K", 12, BASE)

# ---- 2. Ступени, шипы, яма ---------------------------------------------------
g.ground(14, 16, 4)
g.ground(17, 22, 6)
g.put("^", 20, 6)
# бездонная яма 23..25

# ---- 3. Плотный кластер ------------------------------------------------------
g.ground(26, 44, 6)
g.put("^", 27, 6)
g.pit(30, 31)                  # люк над ямой
g.put("T", 30, 5)
g.put("T", 31, 5)
g.put("^", 35, 6)
g.put("C", 40, 9)              # железная коробка — последняя в кластере
g.put("K", 43, 6)

# ---- 4. Башня и лепёшка -------------------------------------------------------
g.ground(45, 46, 8)            # ступенька +2
g.ground(47, 49, 10)           # вершина башни +2: узкий выступ
g.put("C", 48, 13)             # пресс над узким выступом
g.ground(50, 52, BASE)         # падение с 10 на 3 = 7 клеток → лепёшка

# ---- 5. Петля дежавю ----------------------------------------------------------
SEG_LEN = 18


def segment(x0: int):
    """Отрезок, который повторяется дважды символ в символ."""
    g.ground(x0 + 0, x0 + 2, BASE)
    # яма x0+3..x0+5
    g.ground(x0 + 6, x0 + 9, 5)
    g.put("^", x0 + 8, 5)
    g.ground(x0 + 10, x0 + 17, BASE)
    g.put("W", x0 + 11, BASE)
    g.platform(x0 + 11, x0 + 13, 7)
    g.block(x0 + 14, x0 + 17, 8, 9)   # нависающая земля: короткий коридор


LOOP1 = 53
LOOP2 = LOOP1 + SEG_LEN + 1       # между копиями одна колонка с чекпоинтом
segment(LOOP1)
g.ground(LOOP1 + SEG_LEN, LOOP1 + SEG_LEN, BASE)
g.put("K", LOOP1 + SEG_LEN, BASE)
segment(LOOP2)
g.put("*", LOOP2 + 7, 8)          # осколок №1 — только во второй копии, над уступом

# ---- 6. Последняя трава -------------------------------------------------------
AFTER = LOOP2 + SEG_LEN           # 90
g.ground(AFTER, AFTER + 3, BASE)
g.put("K", AFTER + 1, BASE)
g.ground(AFTER + 4, AFTER + 9, 5)  # 94..99 — ровная трава, без ловушек

# ---- 7. Финальный прыжок -------------------------------------------------------
g.ground(100, 104, 5)
g.put("J", 103, 5)
g.pit(105, 108)
g.put("T", 105, 4)                # люк: край ямы, открыть — и яма шире
g.ground(109, W - 1, BASE)        # приземление на 2 ниже; с пружины — лепёшка

# ---- 8. Спокойный путь к двери ---------------------------------------------------
g.put("K", 111, BASE)
g.ground(118, W - 1, 4)
g.put("*", 116, 6)
g.put("F", 122, 4)

