#!/usr/bin/env python3
"""Сборка уровня 06_bunt («Акт VI. Бунт») — экзамен-восхождение «на вершину мира».
Запуск из корня репозитория:

    python3 Design/briefs/06_bunt_build.py

Уровень идёт вверх ярусами: земля y=4 → плато y=10 → ярус петли y=13 → вершина y=19.

Ритм (x):
  0–19    копия начала 01_rozhdenie: старт, первая яма 13..15 (реплика №1), чекпоинт
  20–29   КОНВЕЙЕР по ходу — разгон, в конце ГРИБ O за 2 клетки до стены в 6 клеток
  30–51   ярус-плато y=10, ПЛОТНЫЙ КЛАСТЕР: шипы → люк над шахтой → шипы → пресс над конвейером
          (реплики №2, №3), чекпоинт
  51–61   ПОРТАЛ @ — короткий путь сквозь стену до неба; выход на ярус y=13, чекпоинт
  62–102  ПЕТЛЯ ДЕЖАВЮ: отрезок SEG (20 кол.) дважды символ в символ. Внутри: рассыпающийся мост X,
          вентилятор под нависающей скалой, подъём на платформу и падение-лепёшка на 6 клеток под пресс.
          Между копиями чекпоинт (реплика №4, осколок №1 во второй копии)
  103–108 последняя трава, без ловушек (реплика №5)
  109–124 ЛЁД перед шипами, чекпоинт, пружина под низким потолком, ГРИБ → стена 6 клеток
  125–159 ВЕРШИНА y=19: рассыпающийся мост, конвейер-разгон перед ямой 4 (реплика №6), чекпоинт,
          шипы, пресс, осколок №2, дверь
"""
import sys

sys.path.insert(0, "Tools/levels")
from gridkit import Grid  # noqa: E402

W, H = 160, 23
g = Grid(W, H)

# ---- декор: облачные острова-«глитчи» в небе над стартом (не мешают пути) -----
g.block(4, 8, 14, 14)
g.block(5, 7, 15, 15)
g.block(17, 22, 18, 18)
g.block(40, 43, 20, 21)

# ---- A. Копия начала уровня 1 -----------------------------------------------------
g.ground(0, 12, 4)
g.put("S", 2, 4)
# яма 13..15 — «первая яма в жизни», как в 01_rozhdenie
g.ground(16, 19, 4)
g.put("K", 18, 4)

# ---- B. Конвейер-разгон и гриб у стены ----------------------------------------------
g.ground(20, 29, 4)
g.fill(20, 27, 3, 3, ">")
g.put("O", 28, 3)              # гриб: стена через 2 клетки, +6 вверх

# ---- C. Плато y=10 и плотный кластер -------------------------------------------------
g.ground(30, 52, 10)
g.put("^", 33, 10)
g.pit(36, 37)                  # шахта до низа
g.put("T", 36, 9)
g.put("T", 37, 9)
g.put("^", 41, 10)
g.fill(43, 47, 9, 9, ">")      # конвейер под прессом
g.put("C", 45, 14)
g.put("K", 49, 10)

# ---- D. Портал сквозь стену ------------------------------------------------------------
g.put("@", 51, 10)             # вход — на пути
g.fill(53, 59, 0, H - 1, "#")  # стена до неба
g.ground(60, 61, 13)
g.put("@", 60, 13)             # выход — над опорой
g.put("K", 61, 13)

# ---- E. Петля дежавю --------------------------------------------------------------------
B = 13
SEG_LEN = 20


def segment(s: int):
    """Отрезок, который повторяется дважды символ в символ."""
    g.ground(s + 0, s + 2, B)
    g.fill(s + 3, s + 6, B - 1, B - 1, "X")      # рассыпающийся мост над бездной
    g.ground(s + 7, s + 11, B)
    g.block(s + 4, s + 7, B + 4, B + 5)          # нависающая скала
    g.put("W", s + 7, B)                         # вентилятор — прямо в скалу
    g.ground(s + 10, s + 11, B + 2)              # уступ +2
    g.platform(s + 13, s + 15, B + 4)            # платформа над бездной, стоять на B+5
    g.ground(s + 16, s + 19, B - 1)              # падение 6 клеток — лепёшка
    g.put("C", s + 18, B + 3)                    # пресс над местом приземления


LOOP1 = 62
LOOP2 = LOOP1 + SEG_LEN + 1
segment(LOOP1)
g.ground(LOOP1 + SEG_LEN, LOOP1 + SEG_LEN, B - 1)
g.put("K", LOOP1 + SEG_LEN, B - 1)
segment(LOOP2)
g.put("*", LOOP2 + 14, B + 6)                    # осколок №1 — над платформой второй копии

# ---- F. Последняя трава ----------------------------------------------------------------
AFTER = LOOP2 + SEG_LEN                          # 103
g.ground(AFTER, AFTER + 5, B - 1)

# ---- G. Лёд, шипы, пружина, гриб ----------------------------------------------------------
g.ground(109, 124, B)
g.fill(109, 112, B - 1, B - 1, "~")              # лёд перед шипами
g.put("^", 114, B)
g.put("K", 116, B)
g.put("J", 118, B)
g.block(117, 120, B + 4, B + 5)                  # низкий потолок над пружиной
g.put("O", 123, B - 1)                           # гриб: стена через 2 клетки, +6

# ---- H. Вершина мира y=19 --------------------------------------------------------------------
TOP = 19
g.ground(125, 128, TOP)
g.fill(129, 132, TOP - 1, TOP - 1, "X")          # мост над бездной
g.ground(133, 138, TOP)
g.fill(133, 138, TOP - 1, TOP - 1, ">")          # разгон перед ямой
# яма 139..142
g.ground(143, W - 1, TOP)
g.put("K", 145, TOP)
g.put("^", 148, TOP)
g.put("C", 152, TOP + 3)
g.put("*", 155, TOP + 1)
g.put("F", 158, TOP)

