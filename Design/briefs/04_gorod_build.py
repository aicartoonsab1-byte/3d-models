import sys

sys.path.insert(0, "Tools/levels")
from gridkit import Grid  # noqa: E402

W, H = 124, 16
g = Grid(W, H)
ST = 3  # уровень улицы: шарик стоит на y=3

# 1. Открытая улица, старт, осколок, «эксперимент» под первым прессом (x 0–21)
g.ground(0, 21, ST)
g.put("S", 3, ST)
g.put("*", 8, ST + 1)            # осколок 1: camera.follow(ball)
g.put("C", 18, 7)                # пресс 1: ровная площадка для «эксперимента»

# 2. Дома-ступеньки на крыши + второй пресс (x 22–31)
g.ground(22, 25, 5)
g.ground(26, 31, 7)
g.put("C", 29, 10)               # пресс 2 над крышей

# 3. Прыжок с крыши на крышу через бездонный переулок (x 32–34), крыша h=8 (x 35–39)
g.ground(35, 39, 8)
g.platform(36, 38, 12)           # антенна-перекладина (декор)

# 4. Узкий переулок с шипами (x 40–43): падение-лепёшка с крыши h=8 на дно h=3
#    Над выходом из переулка висит рекламный щит: перепрыгнуть переулок поверху нельзя.
g.ground(40, 43, 2)
g.put("^", 42, 2)
g.ground(44, 45, 4)              # ступенька-крыльцо
g.block(43, 46, 9, 11)           # рекламный щит

# 5. Дом h=6 с чекпоинтом (x 46–51)
g.ground(46, 51, 6)
g.put("K", 48, 6)

# 6. Улица с пружиной (x 52–57) → дом h=6 (x 58–64): лепёшка на крыше после пружины
g.ground(52, 57, ST)
g.put("J", 55, ST)
g.ground(58, 64, 5)

# 7. Башенка h=7 (x 65–67) и мост с люком (x 68–74) над нижней улицей
LOW = 2                          # нижний город: площадь
g.ground(65, 67, 7)
g.ground(68, 80, 1)              # утопленная улица под мостом и аркой
g.block(68, 74, 6, 6)            # мост: пол на y=6, шарик катится по y=7
g.put("T", 71, 6)                # люк → падение на 6 клеток (лепёшка на улице)

# 8. Дом-арка (x 75–80): крыша h=8, под ней проезд высотой 2 для тех, кто упал в люк
g.block(75, 80, 3, 7)

# 9. Площадь Всевидящего (x 81–109): широкая ровная улица, над ней 14 клеток неба
g.ground(81, 109, LOW)
g.put("K", 82, LOW)
g.put("*", 87, LOW + 1)          # осколок 2: observers = 1
g.put("B", 93, LOW)

# 10. Передышка и вентилятор под балконом с шипами (x 103–109)
g.put("W", 107, LOW)
g.platform(106, 108, 7)
g.put("^", 107, 8)

# 11. Последние дома-ступени и выход там, где окна заканчиваются (x 110–123)
g.ground(110, 114, 4)
g.ground(115, 118, 6)
g.ground(119, 123, 8)
g.put("F", 121, 8)

