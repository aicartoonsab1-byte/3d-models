#!/usr/bin/env python3
"""Сборка уровня 04_gorod («Акт IV. Город, который смотрит») — город-фабрика.

Запуск из корня репозитория:  python3 Design/briefs/04_gorod_build.py

Фирменные механики: конвейеры > и < (улица и крыша), грибы-батуты O («сады на крышах»),
спуск по шахте-переулку, площадь Всевидящего.

Ритм (x):
   0– 13  открытая улица, старт, осколок 1 на бугре-ларьке
  14– 21  ровная площадка под прессом 1 на кране — «эксперимент» (реплика 1)
  22– 32  конвейер > по ходу: лента сама несёт шарика под пресс 2 (реплика 2)
  33– 48  утопленный переулок под нависающим домом, шипы на дне (реплика 3)
  46– 57  гриб O у стены → крыша 1 (y=9), пружина J на крыше (реплика 4)
  55– 65  второй гриб → верхняя крыша (y=15), конвейер < против хода под прессом 3
  66– 73  мост между крышами с люком T; под ним нижняя крыша (падение 6 = лепёшка)
  74– 84  нижняя крыша → шахта-переулок с балконом = → улица
  85–118  чекпоинт под аркой, площадь Всевидящего (открытое небо), конвейер > по ходу
 119–149  передышка, чекпоинт, рассыпающийся мост X над бездной, вентилятор,
          лестница крыш с шипами к выходу F «где окна заканчиваются»
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, "Tools/levels")
from gridkit import Grid  # noqa: E402

OUT = Path("Assets/_Project/Resources/Levels/04_gorod.json")
W, H = 150, 20
ST = 3                                   # улица: шарик стоит на y=3
g = Grid(W, H)

# ---------------------------------------------------------------- 1. улица, старт
g.ground(0, 32, ST)
g.ground(9, 11, ST + 1)                  # ларёк-бугорок
g.put("S", 2, ST)
g.put("*", 10, ST + 1)                   # осколок 1: camera.follow(ball)

# ---------------------------------------------------------------- 2. пресс 1 на кране
g.block(14, 20, 8, 10)                   # балкон-навес дома: под ним «коробка»
g.block(15, 18, 11, 12)
g.put("C", 17, 7)

# ---------------------------------------------------------------- 3. конвейер > под пресс 2
g.fill(22, 32, ST - 1, ST - 1, ">")
g.block(28, 34, 8, 9)                    # цех-навес над концом ленты
g.put("C", 31, 7)

# ---------------------------------------------------------------- 4. утопленный переулок с шипами
g.ground(33, 48, ST)
g.fill(38, 41, 1, 2, ".")                # дно переулка на y=1
g.block(36, 43, 8, 12)                   # дом нависает над переулком
g.block(37, 38, 13, 14)                  # надстройка / трубы
g.put("^", 40, 1)

# ---------------------------------------------------------------- 5. сады на крышах: гриб → крыша 1
g.put("O", 46, ST - 1)                   # гриб за 3 клетки до стены
g.ground(49, 57, 9)                      # дом 1, крыша y=9
g.put("J", 52, 9)                        # пружина на крыше: вверх и лепёшкой обратно
g.put("O", 55, 8)                        # второй гриб за 3 клетки до стены дома 2

# ---------------------------------------------------------------- 6. верхняя крыша: конвейер < под прессом 3
g.ground(58, 65, 15)                     # дом 2, крыша y=15
g.fill(59, 65, 14, 14, "<")              # лента против хода: шарик ползёт
g.block(60, 64, 19, 19)                  # балка крана над крышей
g.put("C", 62, 18)

# ---------------------------------------------------------------- 7. мост с люком, нижняя крыша
g.ground(66, 80, 9)                      # нижняя крыша y=9 (под мостом и дальше)
g.block(66, 73, 14, 14)                  # мост между крышами
g.put("T", 69, 14)                       # люк: падение на нижнюю крышу (лепёшка)
g.fill(66, 66, 10, 13, "#")              # опора моста у дома 2
g.block(78, 79, 10, 11)                  # будка выхода на крышу (перепрыгнуть)

# ---------------------------------------------------------------- 8. шахта-переулок и арка
g.ground(81, 149, ST)                    # улица до конца
g.platform(81, 83, 6)                    # балкон в шахте (шарик стоит на y=7)
g.block(85, 92, 9, 16)                   # дом-арка над въездом на площадь
g.block(87, 90, 17, 18)                  # крыша арки
g.put("K", 88, ST)                       # чекпоинт перед Всевидящим
g.put("*", 92, ST)                       # осколок 2: observers = 1

# ---------------------------------------------------------------- 9. площадь Всевидящего
g.put("B", 104, ST)                      # над ним ≥ 7 клеток пустоты по всей площади
g.fill(108, 113, ST - 1, ST - 1, ">")    # лента по ходу: проскочить мимо глаз

# ---------------------------------------------------------------- 10. передышка и выход
g.put("K", 120, ST)
g.pit(125, 128)
g.fill(125, 128, ST - 1, ST - 1, "X")    # рассыпающийся мост над бездной
g.put("W", 131, ST)                      # вентилятор сразу за мостом
g.block(130, 132, 8, 8)                  # вывеска над вентилятором: удар о неё
g.ground(134, 136, 5)                    # ступень-крыша
g.ground(137, 149, 7)                    # крыша с выходом
g.put("^", 139, 7)
g.put("F", 146, 7)

# ---------------------------------------------------------------- мета (тексты из прежней версии)
old = json.loads(OUT.read_text(encoding="utf-8"))
meta = {k: v for k, v in old.items() if k != "grid"}
LINE_X = [13, 22, 34, 43, 65, 94, 102, 118]   # реплики 1–8 из брифа, за 2–4 колонки до места
for line, x in zip(meta["lines"], LINE_X):
    line["x"] = x
g.save(OUT, meta)
g.show()
