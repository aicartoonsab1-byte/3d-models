from gridkit import Grid  # noqa: E402

W, H = 128, 16
g = Grid(W, H)
G = 4          # шарик стоит на y=4
TOP = G - 1    # верхний ряд земли

g.ground(0, W - 1, G)

# ---- A. Старт ---------------------------------------------------------------
g.put("S", 2, G)
g.block(6, 8, 12, 13)                  # крона-декор над стартом

# ---- B. Грязь и первый кокос ----------------------------------------------------
g.fill(13, 17, TOP, TOP, "~")
