# ---- C. Ручей №1: гнилые брёвна, нависающий полог ---------------------------------
g.pit(25, 27)
g.fill(25, 27, TOP, TOP, "X")
g.block(22, 31, 10, 11)                # полог джунглей — коридор
g.put("K", 32, G)

# ---- D. Лист-батут у высокого уступа, обрыв в лепёшку ---------------------------------
g.fill(38, 38, TOP, TOP, "O")          # лист в 3 кл. от уступа
g.ground(41, 50, 10)                   # уступ +6
g.put("^", 46, 10)                     # колючие корни наверху
g.put("*", 38, 7)                      # осколок над листом
# 51.. — обрыв 10→4 (6 клеток) — лепёшка

# ---- E. Грязь под кокосом, корни, ручей №2 ----------------------------------------
g.fill(54, 59, TOP, TOP, "~")
g.put("C", 57, 9)
g.put("^", 61, G)
g.pit(64, 66)
g.fill(64, 66, TOP, TOP, "X")

# ---- F. Яма с водой, чекпоинт ------------------------------------------------------
g.fill(70, 71, 1, 2, ".")              # вода под люком
g.fill(70, 71, TOP, TOP, "T")
g.put("K", 75, G)

# ---- G. Арена Грозовой тучи ---------------------------------------------------------
g.fill(81, 81, G, G + 1, "#")          # коряга-укрытие высотой 2
g.fill(89, 89, G, G, "#")              # пень-укрытие высотой 1
g.put("B", 85, G)
g.put("*", 92, 7)                      # осколок на арене

# ---- H. Лиана-трамплин, ручей №3 -----------------------------------------------------
g.put("J", 97, G)
g.platform(98, 101, 12)                # ветви соседнего дерева (куда подкидывает лиана)
g.pit(102, 104)
g.fill(102, 104, TOP, TOP, "X")
g.put("K", 108, G)

# ---- I. Последний рывок к поляне ------------------------------------------------------
g.fill(110, 113, TOP, TOP, "~")
g.fill(115, 116, 1, 2, ".")
g.fill(115, 116, TOP, TOP, "T")
g.put("W", 118, G)
g.put("C", 120, 9)
g.ground(122, 123, G + 1)              # ступени на поляну
g.ground(124, W - 1, G + 2)
g.put("*", 124, 7)
g.put("F", 126, G + 2)

