# A. Вершина первой горы, старт (0..8), верх y=10
g.ground(0, 8, 10)
g.put("S", 2, 10)
# длинный спуск-конвейер ступенями по 3 колонки (9..26)
h = 9
for x0 in range(9, 27, 3):
    g.ground(x0, x0 + 2, h)
    g.fill(x0, x0 + 2, h - 1, h - 1, ">")
    h -= 1
# B. Долина у подножия (27..39), ямы на дороге
g.ground(27, 39, 4)
g.put("K", 28, 4)
g.fill(32, 33, 0, 2, ".")
