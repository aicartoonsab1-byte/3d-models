# тоннель сквозь гору: вход у подножия, выход на той стороне
g.put("@", 39, 4)
g.ground(40, 50, 13)
g.block(43, 47, 13, 13)          # рваная вершина
g.fill(40, 41, 12, 12, ".")
g.fill(49, 50, 12, 12, ".")
# C. Та сторона горы (51..60): камнепад
g.ground(51, 60, 4)
g.put("@", 52, 4)
g.put("K", 54, 4)
g.put("C", 57, 9)
# подъём на хребет сплошными ступенями
g.ground(61, 63, 6)
g.put("^", 62, 6)
g.ground(64, 66, 8)
g.ground(67, 69, 10)
g.ground(70, 75, 11)
stars.append((73, 13))           # открытка от мамы — на гребне
# осыпающаяся обочина над обрывом (76..79)
g.pit(76, 79)
g.fill(76, 79, 10, 10, "X")
g.ground(80, 86, 11)
g.put("K", 81, 11)
g.fill(83, 86, 10, 10, ">")      # разгон к краю
# D. Обрыв: падение с 7 клеток — лепёшка. Пустыня (87..110)
g.ground(87, 110, 4)
g.put("K", 89, 4)
g.put("^", 93, 4)
g.put("^", 95, 4)
g.put("W", 99, 4)
stars.append((99, 7))            # записка последователя — над Ветром
g.fill(103, 104, 0, 2, ".")
g.put("T", 103, 3); g.put("T", 104, 3)
g.put("W", 107, 4)
# вторая осыпающаяся обочина над обрывом
g.pit(111, 114)
g.fill(111, 114, 3, 3, "X")
# E. Ферма (115..145)
g.ground(115, 123, 4)
g.put("K", 116, 4)
g.put("O", 121, 3)               # стог за 3 клетки до уступа
g.ground(124, 130, 10)           # высокий уступ-амбар
g.ground(131, 133, 8)
g.ground(134, 136, 6)
g.ground(137, 145, 4)
stars.append((135, 8))           # письмо от Вишенки
g.put("J", 139, 4)               # кочка-трамплин
g.put("C", 141, 9)
g.put("W", 142, 4)
g.put("F", 144, 4)

