import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
sys.path.insert(0, str(ROOT / "Tools/levels"))
from gridkit import Grid  # noqa: E402

W, H = 130, 16
g = Grid(W, H)

# ---- поле --------------------------------------------------------------------
g.ground(0, W - 1, 4)
g.put("S", 2, 4)
# первая беговая дорожка и яма
g.fill(11, 17, 3, 3, ">")
g.pit(18, 20)
# бутсы и мяч
g.put("^", 25, 4)
g.put("C", 29, 9)
# встречная дорожка
g.fill(31, 36, 3, 3, "<")
g.put("*", 34, 6)                 # программка матча
g.put("^", 39, 4)
g.put("K", 42, 4)
# мокрый газон под мячами, яма за ним
g.fill(44, 52, 3, 3, "~")
g.put("C", 47, 9)
g.put("C", 50, 9)
g.pit(53, 55)
# подтрибунный коридор и раздевалка
g.block(57, 63, 8, H - 1)
g.put("@", 62, 4)                 # дверь раздевалки (вход)
g.ground(64, 65, H)               # глухая стена
g.block(66, 70, 10, H - 1)
g.put("@", 67, 4)                 # выход из раздевалки
g.put("K", 71, 4)
# трибуны-ступени: с 4 до 10
for i, h in enumerate(range(5, 11)):
    g.ground(74 + 2 * i, 75 + 2 * i, h)
g.ground(86, 92, 10)
g.put("W", 88, 10)                # порыв с трибун
g.put("*", 90, 12)                # открытка без подписи
# 93: падение с трибуны на поле (6 клеток)
# люки под трибунами
g.fill(96, 99, 1, 2, ".")
for x in (97, 98):
    g.put("T", x, 3)
g.put("K", 102, 4)
# трамплин-мат, дорожка, бутсы
g.put("J", 106, 4)
g.fill(109, 114, 3, 3, ">")
g.put("^", 116, 4)
g.put("*", 119, 6)                # записка тренера
g.put("C", 122, 9)                # табло
g.block(124, 129, 11, 11)         # козырёк над воротами
g.put("F", 128, 4)

