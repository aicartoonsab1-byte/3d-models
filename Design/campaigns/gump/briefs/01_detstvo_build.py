g.put("B", 86, 4)
g.block(80, 83, 12, 13)           # облака высоко над ареной
g.block(90, 93, 12, 12)

# школьный двор
g.put("J", 98, 4)
g.put("*", 102, 5)                # рисунок Вишенки
g.ground(104, 117, 5)             # крыльцо школы +1
g.block(110, 110, 6, 9)           # столб школы
