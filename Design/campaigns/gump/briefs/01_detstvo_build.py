g.block(47, 49, 13, 13)           # ветка над пригорком (декор)

# горка под уклон 54..60
for x, h in zip(range(54, 61), (10, 10, 9, 9, 9, 8, 8)):
    g.ground(x, x, h)
    g.put(">", x, h - 1)

# низина (обрыв 8→3 — лепёшка)
g.ground(61, 75, 3)
g.fill(66, 67, 1, 2, ".")         # канава
g.put("T", 66, 2); g.put("T", 67, 2)
