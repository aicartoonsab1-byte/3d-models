from gridkit import Grid  # noqa: E402

W, H = 130, 18
g = Grid(W, H)
DECK = 8

# ---- A. Палуба, старт ------------------------------------------------------------
g.ground(0, 45, DECK)
g.put("S", 2, DECK)
g.block(9, 9, 13, 16)                  # мачта-декор
g.platform(7, 11, 14)                  # рея

# ---- B. Крен палубы: > по ходу, затем < навстречу --------------------------------
g.fill(14, 19, DECK - 1, DECK - 1, ">")
g.fill(20, 24, DECK - 1, DECK - 1, "<")

# ---- C. Мокрая палуба у борта, крючок, борт-яма -----------------------------------
g.fill(25, 29, DECK - 1, DECK - 1, "~")
g.put("^", 30, DECK)                   # рыболовный крючок
g.pit(32, 34)                          # за бортом — море

# ---- D. Передышка, чекпоинт, ящик с рыбой, мачта с осколком -----------------------
g.ground(35, 45, DECK)
g.put("K", 36, DECK)
g.put("C", 39, 12)                     # ящик с рыбой срывается со штабеля
g.block(43, 43, 13, 16)                # мачта
g.platform(41, 45, 10)                 # марс (стоять на y=11)
g.put("*", 42, 13)                     # осколок: вывеска «БЛИНЫ У МОРЯ»

# ---- E. Трюм: пол y=2, палуба с люком, провал -------------------------------------
g.fill(46, 103, 0, 1, "#")             # пол трюма (стоять на y=2)
g.fill(46, 50, 2, 5, ".")
g.fill(46, 48, 6, 7, "#")              # палуба над трюмом
g.fill(47, 47, 6, 6, ".")              # под люком пусто
g.put("T", 47, 7)                      # люк трюма
# 49..50 — открытый проём, падение 8→2 = 6 клеток
g.fill(51, 90, 7, 8, "#")              # низкий потолок трюма = верхняя палуба
g.fill(51, 53, 9, 13, "#")             # рубка: поверху трюм не обойти
g.fill(52, 53, 14, 15, "#")

for x in (58, 61, 64):                 # ящики с рыбой под потолком
    g.put("C", x, 6)
g.put("*", 67, 3)                      # осколок: судовой журнал капитана
g.put("K", 70, 2)

# ---- F. Арена Волны-великана --------------------------------------------------------
g.put("B", 81, 2)

# ---- G. Подъём из трюма: сеть-батут, ступени +2, ветер ------------------------------
g.put("J", 94, 2)                      # натянутая сеть-батут
g.fill(96, 97, 2, 3, "#")              # сплошные ступени по +2
g.fill(98, 99, 2, 5, "#")
g.fill(100, 101, 2, 7, "#")
g.put("W", 99, 6)                      # штормовой ветер у мачты
g.block(97, 97, 11, 15)                # грот-мачта над подъёмом (декор)
g.ground(102, 129, 10)                 # нос, стоять на y=10

# ---- H. Нос лодки -------------------------------------------------------------------
g.put("K", 106, 10)
g.fill(110, 114, 9, 9, "<")            # встречный крен
g.put("^", 116, 10)                    # крючок на носу
g.fill(117, 121, 9, 9, ">")
g.put("C", 119, 14)                    # последний ящик с рыбой
g.put("*", 123, 11)                    # осколок: письмо от Вишенки
g.block(125, 126, 15, 15)              # бушприт-декор
g.put("F", 128, 10)

