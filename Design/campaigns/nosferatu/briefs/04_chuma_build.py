g.ground(128, 132, 12)             # мансарда, стоим на y=12
g.platform(124, 127, 13)           # бельевая перекладина над крышей
g.put("*", 130, 14)                # страница из книги Лины
g.ground(133, W - 1, 13)           # верхняя крыша у окна Лины, стоим на y=13
