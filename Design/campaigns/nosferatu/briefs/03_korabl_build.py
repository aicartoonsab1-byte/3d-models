sys.path.insert(0, "Tools/levels")
from gridkit import Grid  # noqa: E402

W, H = 130, 18
g = Grid(W, H)
DECK = 8

# ---- A. Палуба, старт ------------------------------------------------------------
g.ground(0, 43, DECK)
g.put("S", 2, DECK)
# мачта-декор: рея над головой
g.block(9, 9, 13, 16)
g.platform(7, 11, 14)

# ---- B. Крен палубы: > по ходу, < под тюком ----------------------------------------
g.fill(15, 20, DECK - 1, DECK - 1, ">")
g.fill(21, 25, DECK - 1, DECK - 1, "<")
g.put("C", 23, 12)                     # падающий тюк над встречным креном

# ---- C. Мокрые доски у сломанных поручней, борт-яма ------------------------------
g.fill(26, 30, DECK - 1, DECK - 1, "~")
g.put("^", 31, DECK)
g.pit(33, 35)                          # за бортом — море
g.ground(36, 43, DECK)

# ---- D. Передышка, чекпоинт, мачта с осколком ---------------------------------
g.put("K", 38, DECK)
g.block(41, 41, 13, 16)                # мачта
g.platform(39, 43, 10)                 # марс (стоять на y=11)
g.put("*", 40, 13)                     # осколок №1: судовой журнал на мачте

# ---- E. Трюм: пол y=2, мост-палуба с люком, провал ------------------------------
g.fill(44, 103, 0, 1, "#")             # пол трюма (стоять на y=2)
g.fill(44, 48, 6, 7, "#")              # палуба над трюмом
g.put("T", 46, 7)                      # люк трюма (под ним пусто)
g.fill(46, 46, 2, 6, ".")
g.fill(45, 45, 2, 5, ".")
g.fill(47, 47, 2, 5, ".")
g.fill(44, 48, 2, 5, ".")
# 49..50 — открытый люк, падение 8→2 = 6 клеток
g.fill(51, 90, 7, 8, "#")              # низкий потолок трюма = верхняя палуба
g.fill(51, 53, 9, 13, "#")             # надстройка: поверху трюм не обойти
g.fill(52, 53, 14, 15, "#")

# гробы-прессы ровным рядом
for x in (58, 61, 64):
    g.put("C", x, 6)
g.put("*", 67, 3)                      # осколок №2 за гробами
g.put("K", 70, 2)

# ---- F. Арена крыс -----------------------------------------------------------------
g.put("B", 81, 2)

# ---- G. Подъём по вантам, рея, ветер ------------------------------------------
g.put("J", 94, 2)                      # качающаяся рея
g.fill(96, 97, 2, 3, "#")              # штабели ящиков ступенями по +2
g.fill(98, 99, 2, 5, "#")
g.fill(100, 101, 2, 7, "#")
g.put("W", 99, 6)                      # штормовой ветер на подъёме
g.platform(97, 100, 11)                # ванты-рея над подъёмом (можно запрыгнуть)
g.platform(93, 95, 13)
g.ground(102, 129, 10)                 # бак, стоять на y=10

# ---- H. Нос корабля ------------------------------------------------------------------
g.put("K", 106, 10)
g.fill(111, 116, 9, 9, "<")            # встречный крен
g.fill(117, 120, 9, 9, ">")
g.put("*", 122, 11)                    # осколок №3 у носа
g.block(124, 125, 15, 15)              # бушприт-декор
g.put("F", 127, 10)

